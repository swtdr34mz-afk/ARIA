/* The MPC build's parameter tables: the MPC SDK compiles C++ only, and dsp/params_data.c uses C's designated
 * initialisers. Built natively (as C) and run by mpc/build.py, this writes them out in order:
 *
 *   gen_params <params_data.cpp> <params.json>
 *
 * params_data.cpp: the same tables as C++; params.json: each parameter's index, MPC name, kind and choices (for
 * mpc/pages.py, which makes the MPC's screen pages). */
#include "aria.h"
#include <stdio.h>

static void esc(FILE *f, const char *s)
{
    fputc('"', f);
    for (; *s; s++) { if (*s == '"' || *s == '\\') fputc('\\', f); fputc(*s, f); }
    fputc('"', f);
}

static const char *const *seen[ARIA_NPARAM];
static int nseen;
static int choice_id(const char *const *c)
{
    for (int i = 0; i < nseen; i++) if (seen[i] == c) return i;
    seen[nseen] = c;
    return nseen++;
}

static void table(FILE *f, const char *name, const aria_param_t *t, int n, const char *size)
{
    fprintf(f, "extern \"C\" const aria_param_t %s[%s] = {\n", name, size);
    for (int i = 0; i < n; i++) {
        fprintf(f, "    { ");
        esc(f, t[i].name);
        if (t[i].kind == PK_CHOICE) fprintf(f, ", %d, %d, %.6ff, CH%d },\n", t[i].kind, t[i].count, t[i].def, choice_id(t[i].choice));
        else fprintf(f, ", %d, %d, %.6ff, nullptr },\n", t[i].kind, t[i].count, t[i].def);
    }
    fprintf(f, "};\n");
}

int main(int argc, char **argv)
{
    if (argc < 3) return 2;
    FILE *f = fopen(argv[1], "w"), *j = fopen(argv[2], "w");
    if (!f || !j) return 1;
    fprintf(f, "/* generated by mpc/gen/gen_params.c from dsp/params_data.c: do not edit */\n#include \"aria.h\"\n\n");
    for (int p = 0; p < ARIA_NPARAM; p++) {
        const aria_param_t *d = aria_param_info(p);
        if (d->kind != PK_CHOICE) continue;
        int before = nseen, id = choice_id(d->choice);
        if (id < before) continue;
        fprintf(f, "static const char *const CH%d[] = { ", id);
        for (int k = 0; k < d->count; k++) { if (k) fprintf(f, ", "); esc(f, d->choice[k]); }
        fprintf(f, " };\n");
    }
    fprintf(f, "\n");
    table(f, "ARIA_TPARAMS", ARIA_TPARAMS, TP_COUNT, "TP_COUNT");
    table(f, "ARIA_GPARAMS", ARIA_GPARAMS, ARIA_NPARAM - GP_FIRST, "ARIA_NPARAM - GP_FIRST");
    fprintf(f, "extern \"C\" const char *const ARIA_TSHORT[TP_COUNT] = {\n");
    for (int i = 0; i < TP_COUNT; i++) { fprintf(f, "    "); esc(f, ARIA_TSHORT[i]); fprintf(f, ",\n"); }
    fprintf(f, "};\nextern \"C\" const char *const ARIA_GSHORT[ARIA_NPARAM - GP_FIRST] = {\n");
    for (int i = 0; i < ARIA_NPARAM - GP_FIRST; i++) { fprintf(f, "    "); esc(f, ARIA_GSHORT[i]); fprintf(f, ",\n"); }
    fprintf(f, "};\n");
    fclose(f);
    /* params.json */
    fprintf(j, "[\n");
    for (int p = 0; p < ARIA_NPARAM; p++) {
        const aria_param_t *d = aria_param_info(p);
        char s[32];
        aria_param_short(p, s, (int)sizeof s);
        fprintf(j, "  {\"index\": %d, \"name\": ", p); esc(j, s);
        fprintf(j, ", \"kind\": \"%s\", \"def\": %.4f, \"choices\": [",
                d->kind == PK_CHOICE ? "choice" : d->kind == PK_SWITCH ? "switch" : d->kind == PK_BIPOLAR ? "bipolar" : "knob", d->def);
        if (d->kind == PK_CHOICE) for (int k = 0; k < d->count; k++) { if (k) fprintf(j, ", "); esc(j, d->choice[k]); }
        fprintf(j, "]}%s\n", p < ARIA_NPARAM - 1 ? "," : "");
    }
    fprintf(j, "]\n");
    fclose(j);
    return 0;
}
